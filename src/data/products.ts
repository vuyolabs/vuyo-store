const productMap = new Map(products.map((p) => [p.id, p]));

export function getProduct(id: string): Product | undefined {
  return productMap.get(id);
}

export function getProductsByCollection(collectionId: string): Product[] {
  return products.filter((p) => p.collections.includes(collectionId));
}

/** Same category first, then shared collections, excluding the product itself. */
export function getRelatedProducts(productId: string, limit = 6): Product[] {
  const base = productMap.get(productId);
  if (!base) return [];
  const scored = products
    .filter((p) => p.id !== base.id)
    .map((p) => {
      const sameCategory = p.category === base.category ? 2 : 0;
      const sharedCollections = p.collections.filter((c) => base.collections.includes(c)).length;
      return { p, score: sameCategory + sharedCollections };
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score || b.p.rating - a.p.rating);
  return scored.slice(0, limit).map((x) => x.p);
}

